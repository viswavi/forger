"""Generate ``docs/OPS.md``: the signature of every public Forger op.

Run from the repository root after adding, renaming, or changing the signature or
docstring of any public op (``tests/test_op_docs.py`` fails until you do)::

    python scripts/gen_op_docs.py

Each export in ``__all__`` of ``pyforger.acquire``, ``pyforger.alter``,
``pyforger.alter.translate``, ``pyforger.filter``, and ``pyforger.inspect`` gets an
entry: its call signature, whether it is disk-cached, and the first paragraph and
``Returns:`` section of its docstring (``Args:`` is left out; the signature covers
it). Classes are documented only when listed in ``ENTRY_POINT_CLASSES`` (classes
users construct and pass to ops); other exported classes are named in one line.
Annotations and defaults are copied from the source text, e.g.
``mode: RetrieveMode = RetrieveMode.QUERY``, so the output does not depend on how a
Python version prints objects.
"""

from __future__ import annotations

import argparse
import ast
import importlib
import inspect
import json
import sys
import textwrap
from pathlib import Path
from types import ModuleType
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
# Document this checkout's code, not an installed pyforger.
sys.path.insert(0, str(REPO_ROOT / "src"))

from pyforger.op import OP_INFO_ATTR  # noqa: E402

OUTPUT = REPO_ROOT / "docs" / "OPS.md"
REGENERATE = "python scripts/gen_op_docs.py"

# Documented in this order. A submodule exported by a module (``alter.translate``)
# is not an op; it gets its own section here instead.
MODULES = [
    "pyforger.acquire",
    "pyforger.alter",
    "pyforger.alter.translate",
    "pyforger.filter",
    "pyforger.inspect",
]

# Exported classes that users construct and pass to ops; documented by __init__.
ENTRY_POINT_CLASSES = {
    "Model",
    "LocalModel",
    "WebRetrievalSource",
    "WikiRetrievalSource",
    "HFRetrievalSource",
    "ArxivRetrievalSource",
    "S2RetrievalSource",
}

MAX_WIDTH = 120

HEADER = f"""\
# Forger op reference

<!-- Generated by scripts/gen_op_docs.py; do not edit by hand. -->

The call signature of every public op, generated from the code. Regenerate with
`{REGENERATE}` after adding or changing an op. See [AGENTS.md](AGENTS.md)
for how ops fit into steps and pipelines.

Each op has a stable anchor: its module and name, lowercase, joined by `-`, e.g.
`OPS.md#filter-by_llm_score` or `OPS.md#alter-translate-to_code`.

Keywords left out of the signatures below:

- `min_yield=` / `max_yield=`: the expected range of output rows over input rows,
  checked in the step report. Every `@op` that takes input rows (the `alter`,
  `filter`, and `inspect` ops marked `@op`) accepts them; `acquire` ops reject them.
- `_no_cache=True` (skip the cache for this call and the ops it makes) and
  `_cache_only=True` (return a cached result or raise `FileNotFoundError`): every
  op marked disk-cached.
"""


def _public_names(module: ModuleType) -> list[str]:
    """Return ``__all__``, or public functions defined in the module, by name."""
    names = getattr(module, "__all__", None)
    if names is not None:
        return list(names)
    return sorted(
        name
        for name, obj in vars(module).items()
        if not name.startswith("_")
        and inspect.isfunction(obj)
        and obj.__module__ == module.__name__
    )


def _source_def(obj: Any) -> tuple[ast.FunctionDef | None, str]:
    """Return the AST and source of a function (or a class's ``__init__``)."""
    target = obj.__init__ if inspect.isclass(obj) else inspect.unwrap(obj)
    try:
        source = textwrap.dedent(inspect.getsource(target))
    except (OSError, TypeError):
        return None, ""
    node = ast.parse(source).body[0]
    return (node if isinstance(node, ast.FunctionDef) else None), source


def _source_text(node: ast.AST | None, source: str) -> str | None:
    """Return a node's text as written, on one line (``ast.unparse`` if wrapped)."""
    if node is None:
        return None
    text = ast.get_source_segment(source, node)
    if text is None or "\n" in text:
        text = ast.unparse(node)
    return text


def _param_texts(obj: Any) -> tuple[dict[str, tuple[str | None, str | None]], str]:
    """Map each parameter to its (annotation, default) source text; also the return.

    Example: ``{"n": ("int", "10")}`` and ``"list[dict]"`` for
    ``def f(n: int = 10) -> list[dict]``.
    """
    node, source = _source_def(obj)
    if node is None:
        return {}, ""
    args = node.args
    texts: dict[str, tuple[str | None, str | None]] = {}
    positional = args.posonlyargs + args.args
    pos_defaults: list[ast.expr | None] = [None] * (
        len(positional) - len(args.defaults)
    ) + list(args.defaults)
    for arg, default in zip(positional, pos_defaults):
        texts[arg.arg] = (
            _source_text(arg.annotation, source),
            _source_text(default, source),
        )
    for arg, kw_default in zip(args.kwonlyargs, args.kw_defaults):
        texts[arg.arg] = (
            _source_text(arg.annotation, source),
            _source_text(kw_default, source),
        )
    for star in (args.vararg, args.kwarg):
        if star is not None:
            texts[star.arg] = (_source_text(star.annotation, source), None)
    returns = "" if inspect.isclass(obj) else _source_text(node.returns, source) or ""
    return texts, returns


def _format_param(
    param: inspect.Parameter, annotation: str | None, default: Any
) -> str:
    """Render one parameter, e.g. ``n: int = 10``, ``*args``, ``**kwargs: Any``."""
    prefix = ""
    if param.kind is param.VAR_POSITIONAL:
        prefix = "*"
    elif param.kind is param.VAR_KEYWORD:
        prefix = "**"
    text = prefix + param.name
    if annotation:
        text += f": {annotation}"
    if default is not None:
        text += f" = {default}" if annotation else f"={default}"
    return text


def _literal(value: Any) -> str | None:
    """Render a short scalar default as source, e.g. ``"en"``; None otherwise."""
    if isinstance(value, str):
        text = json.dumps(value, ensure_ascii=False)
    elif value is None or isinstance(value, (bool, int, float)):
        text = repr(value)
    else:
        return None
    return text if len(text) <= 60 else None


def render_signature(name: str, obj: Any) -> str:
    """Return ``name(...) -> ret``, one parameter per line if over 120 chars."""
    sig = inspect.signature(obj if inspect.isclass(obj) else inspect.unwrap(obj))
    texts, returns = _param_texts(obj)
    parts: list[str] = []
    prev_kind = None
    for param in sig.parameters.values():
        annotation, default = texts.get(param.name, (None, None))
        if annotation is None and param.annotation is not param.empty:
            annotation = inspect.formatannotation(param.annotation)
        if param.default is not param.empty and (
            default is None or default.startswith("_")
        ):
            # A private constant means nothing to callers; show its value instead,
            # e.g. "Qwen/Qwen3-Embedding-0.6B" for _DEFAULT_EMBEDDING_MODEL.
            default = _literal(param.default) or default or "..."
        if prev_kind is param.POSITIONAL_ONLY and param.kind is not prev_kind:
            parts.append("/")
        if param.kind is param.KEYWORD_ONLY and prev_kind not in (
            param.KEYWORD_ONLY,
            param.VAR_POSITIONAL,
        ):
            parts.append("*")
        parts.append(_format_param(param, annotation, default))
        prev_kind = param.kind
    if prev_kind is inspect.Parameter.POSITIONAL_ONLY:
        parts.append("/")
    if not returns and sig.return_annotation is not sig.empty:
        if not inspect.isclass(obj):
            returns = inspect.formatannotation(sig.return_annotation)
    tail = f") -> {returns}" if returns else ")"
    one_line = f"{name}({', '.join(parts)}{tail}"
    if len(one_line) <= MAX_WIDTH:
        return one_line
    body = "".join(f"    {part},\n" for part in parts)
    return f"{name}(\n{body}{tail}"


def _markdown(paragraph: str) -> str:
    """Join a docstring paragraph into Markdown wrapped at 120 chars."""
    text = " ".join(line.strip() for line in paragraph.splitlines())
    return textwrap.fill(
        text.replace("``", "`"),
        width=MAX_WIDTH,
        break_long_words=False,
        break_on_hyphens=False,
    )


def _first_paragraph(obj: Any) -> str:
    """Return the docstring's first paragraph, in Markdown, wrapped at 120 chars."""
    doc = inspect.getdoc(obj) or ""
    paragraph = doc.strip().split("\n\n", 1)[0]
    return _markdown(paragraph) if paragraph.strip() else "_No docstring._"


def _returns_section(obj: Any) -> str | None:
    """Return the docstring's ``Returns:`` section in Markdown, or None if absent.

    It says which fields an op writes, e.g. ``thinking_trace``. The section ends at
    the next unindented line, e.g. ``Raises:`` or ``Note:``.
    """
    lines = (inspect.getdoc(obj) or "").splitlines()
    if "Returns:" not in lines:
        return None
    body: list[str] = []
    for line in lines[lines.index("Returns:") + 1 :]:
        if line.strip() and not line[0].isspace():
            break
        body.append(line)
    paragraphs = [p for p in "\n".join(body).split("\n\n") if p.strip()]
    if not paragraphs:
        return None
    paragraphs[0] = "**Returns:** " + paragraphs[0].strip()
    return "\n\n".join(_markdown(p) for p in paragraphs)


def anchor(qualified: str) -> str:
    """The stable anchor of an op or module, e.g. ``filter-by_llm_score``.

    GitHub's own heading anchors drop the dots (``filterby_llm_score``), so
    each heading gets an explicit ``<a name=...>`` instead.
    """
    return qualified.lower().replace(".", "-")


def _anchor_tag(qualified: str) -> str:
    return f'<a name="{anchor(qualified)}"></a>'


def _entry(name: str, qualified: str, obj: Any) -> str:
    """Render one op: heading, caching status, signature, docstring summary."""
    parts = [
        _anchor_tag(qualified),
        f"### `{qualified}`",
        _status(obj, qualified),
        f"```python\n{render_signature(name, obj)}\n```",
        _first_paragraph(obj),
    ]
    returns = _returns_section(obj)
    if returns is not None:
        parts.append(returns)
    return "\n\n".join(parts) + "\n"


def _op_info(obj: Any) -> dict[str, Any] | None:
    """Return the ``@op`` / tracked info of ``obj`` or of the one op it wraps.

    A plain function that calls exactly one op from its module's globals takes
    that op's info, e.g. ``retrieve_from_web`` calling ``retrieve``, or a public
    ``topic_based_clustering`` calling a cached ``_topic_based_clustering``.
    """
    info = getattr(obj, OP_INFO_ATTR, None)
    if info is not None or not inspect.isfunction(obj):
        return info
    called = {
        getattr(obj.__globals__[name], OP_INFO_ATTR)["name"]: getattr(
            obj.__globals__[name], OP_INFO_ATTR
        )
        for name in obj.__code__.co_names
        if hasattr(obj.__globals__.get(name), OP_INFO_ATTR)
    }
    return next(iter(called.values())) if len(called) == 1 else None


def _status(obj: Any, qualified: str) -> str:
    """Describe caching, e.g. "Disk-cached (`@op`)." or "Not cached."."""
    if inspect.isclass(obj):
        return "Class: construct it and pass it to ops."
    info = _op_info(obj)
    if info is None:
        return "Not cached: a plain function."
    named = "" if info["name"] == qualified else f" named `{info['name']}`"
    if info["kind"] == "tracked":
        return (
            "Not cached (wrap it with `@op` to memoize); listed in step reports as "
            f"`{info['name']}`."
        )
    if info["cache"]:
        return f"Disk-cached (`@op`{named})."
    return f"`@op`{named} with caching off: listed in step reports, runs on every call."


def _exports(module: ModuleType) -> tuple[list[tuple[str, Any]], list[str]]:
    """Split a module's exports into documented ``(name, obj)`` and skipped names."""
    documented: list[tuple[str, Any]] = []
    skipped: list[str] = []
    for name in _public_names(module):
        obj = getattr(module, name)
        if inspect.ismodule(obj):
            continue
        if inspect.isclass(obj) and name not in ENTRY_POINT_CLASSES:
            skipped.append(name)
            continue
        if not callable(obj):
            skipped.append(name)
            continue
        documented.append((name, obj))
    return documented, skipped


def _module_section(module_name: str) -> str:
    """Render one ``## module`` section with an entry per documented export."""
    module = importlib.import_module(module_name)
    short = module_name.removeprefix("pyforger.")
    documented, skipped = _exports(module)
    entries = [_entry(name, f"{short}.{name}", obj) for name, obj in documented]
    section = (
        f"{_anchor_tag(short)}\n\n## `{module_name}`\n\n{_first_paragraph(module)}\n"
    )
    if skipped:
        names = ", ".join(f"`{n}`" for n in skipped)
        section += f"\nAlso exported, not documented here: {names}.\n"
    return "\n".join([section, *entries])


def _toc_line(text: str, indent: str) -> str:
    """One list item, wrapped at 120 chars with continuation lines indented."""
    return textwrap.fill(
        text,
        width=MAX_WIDTH,
        initial_indent=f"{indent}- ",
        subsequent_indent=f"{indent}  ",
        break_long_words=False,
        break_on_hyphens=False,
    )


def render_toc() -> str:
    """Return the ``## Contents`` list: each module, then its ops with a summary.

    Example item: ``- [`by_length`](#filter-by_length): Keep items whose ...``.
    """
    lines = ["## Contents", ""]
    seen = {anchor(m.removeprefix("pyforger.")) for m in MODULES}
    for module_name in MODULES:
        short = module_name.removeprefix("pyforger.")
        documented, _ = _exports(importlib.import_module(module_name))
        lines.append(f"- [`{module_name}`](#{anchor(short)})")
        for name, obj in documented:
            target = anchor(f"{short}.{name}")
            if target in seen:  # e.g. ops `by_LLM` and `by_llm`
                raise ValueError(f"two entries share the anchor {target!r}")
            seen.add(target)
            summary = _first_paragraph(obj).replace("\n", " ")
            lines.append(_toc_line(f"[`{name}`](#{target}): {summary}", "  "))
    return "\n".join(lines) + "\n"


def render() -> str:
    """Return the full text of ``docs/OPS.md``."""
    return "\n".join([HEADER, render_toc(), *(_module_section(m) for m in MODULES)])


def main(argv: list[str] | None = None) -> int:
    """Write ``docs/OPS.md``; with ``--check``, exit 1 if it is out of date."""
    parser = argparse.ArgumentParser(description="Generate docs/OPS.md.")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if docs/OPS.md is stale"
    )
    args = parser.parse_args(argv)
    text = render()
    current = OUTPUT.read_text() if OUTPUT.exists() else None
    if args.check:
        if current != text:
            print(f"{OUTPUT} is out of date; run {REGENERATE}", file=sys.stderr)
            return 1
        return 0
    if current != text:
        OUTPUT.write_text(text)
        print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
